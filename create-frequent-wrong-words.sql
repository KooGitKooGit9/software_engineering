create table if not exists frequent_wrong_words (
  id bigint generated by default as identity primary key,
  word text not null unique,
  category text,
  level text,
  wrong_count integer not null default 3,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function set_frequent_wrong_words_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists frequent_wrong_words_updated_at on frequent_wrong_words;

create trigger frequent_wrong_words_updated_at
before update on frequent_wrong_words
for each row
execute function set_frequent_wrong_words_updated_at();

alter table frequent_wrong_words enable row level security;

drop policy if exists "allow public read frequent wrong words" on frequent_wrong_words;
drop policy if exists "allow public insert frequent wrong words" on frequent_wrong_words;
drop policy if exists "allow public update frequent wrong words" on frequent_wrong_words;

create policy "allow public read frequent wrong words"
on frequent_wrong_words
for select
using (true);

create policy "allow public insert frequent wrong words"
on frequent_wrong_words
for insert
with check (true);

create policy "allow public update frequent wrong words"
on frequent_wrong_words
for update
using (true)
with check (true);

insert into frequent_wrong_words (word, category, level, wrong_count)
select
  word,
  max(category) as category,
  max(level) as level,
  count(*)::integer as wrong_count
from wrong_history
group by word
having count(*) >= 3
on conflict (word) do update set
  category = excluded.category,
  level = excluded.level,
  wrong_count = excluded.wrong_count;
