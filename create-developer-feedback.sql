create table if not exists developer_feedback (
  id bigint generated by default as identity primary key,
  message text not null,
  page_context text,
  user_agent text,
  created_at timestamptz not null default now()
);

alter table developer_feedback enable row level security;

drop policy if exists "allow public insert developer feedback" on developer_feedback;

create policy "allow public insert developer feedback"
on developer_feedback
for insert
with check (true);
