-- 1. Words Table
create table if not exists words (
  id bigint generated by default as identity primary key,
  word text not null unique,
  meaning text not null,
  pronunciation text,
  category text,
  level text,
  example text,
  example_kor text,
  image_url text,
  created_at timestamptz not null default now()
);

alter table words enable row level security;
drop policy if exists "allow public read words" on words;
create policy "allow public read words" on words for select using (true);

-- 2. Correct History Table
create table if not exists correct_history (
  id bigint generated by default as identity primary key,
  word text not null,
  category text,
  level text,
  created_at timestamptz not null default now()
);

alter table correct_history enable row level security;
drop policy if exists "allow public read correct_history" on correct_history;
drop policy if exists "allow public insert correct_history" on correct_history;
create policy "allow public read correct_history" on correct_history for select using (true);
create policy "allow public insert correct_history" on correct_history for insert with check (true);

-- 3. Wrong History Table
create table if not exists wrong_history (
